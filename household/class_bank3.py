def _mean(word: str, answer: str, subject: str = "English"):
    return (subject, [f"What does '{word}' mean?", f"What is the meaning of {word}?", f"Explain the word {word}.",
                      f"If someone says {word}, what do they mean?"], answer)


def _opp(word: str, other: str):
    return ("English", [f"What is the opposite of {word}?", f"Opposite of {word}?", f"What word means the opposite of {word}?",
                        f"If something is not {word}, what is it?"], f"{other} is the opposite of {word}")


