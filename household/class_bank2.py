def _what(thing: str, answer: str, subject: str):
    return (subject, [f"What is {thing}?", f"Tell me about {thing}.", f"Explain {thing} to me.",
                      f"Do you know what {thing} is?"], answer)


def _how(task: str, answer: str, subject: str):
    return (subject, [f"How do you {task}?", f"How can I {task}?", f"Show me how to {task}.",
                      f"What are the steps to {task}?"], answer)


def _why(thing: str, answer: str, subject: str):
    return (subject, [f"Why {thing}?", f"Can you tell me why {thing}?", f"Explain why {thing}.",
                      f"Do you know why {thing}?"], answer)


